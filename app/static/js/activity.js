/* Minimal first-party usage: trusted interaction on a visible, signed-in page. */
(() => {
  'use strict';
  const token = document.querySelector('meta[name="activity-csrf"]')?.content;
  if (!token) return;
  const interval = 60000;
  let interactedAt = 0, attemptedAt = Date.now(), busy = false, stopped = false;

  async function pulse() {
    const now = Date.now();
    if (stopped || busy || document.hidden || !navigator.onLine ||
        !interactedAt || now - interactedAt > interval || now - attemptedAt < interval) return;
    attemptedAt = now;
    busy = true;
    try {
      const response = await fetch('/activity/pulse', {
        method: 'POST', credentials: 'same-origin', cache: 'no-store',
        headers: {'Accept': 'application/json'},
        body: new URLSearchParams({csrf_token: token}), signal: AbortSignal.timeout(15000),
      });
      if (response.redirected || [400, 401, 403].includes(response.status)) stopped = true;
    } catch (_) { /* A later interaction can retry; usage never interrupts a member. */ }
    finally { busy = false; }
  }
  function interaction(event) {
    if (!event.isTrusted || document.hidden) return;
    interactedAt = Date.now();
    pulse();
  }
  // Scroll events can be browser-trusted even when generated by script (for
  // example, a conversation scrolling to a newly polled message). Observe the
  // person's wheel/touch/key/pointer input instead of the resulting scrolling.
  for (const name of ['pointerdown', 'keydown', 'wheel', 'touchstart', 'touchmove']) {
    document.addEventListener(name, interaction, {passive: true, capture: true});
  }
  window.addEventListener('focus', interaction);
  document.addEventListener('visibilitychange', event => {
    if (document.hidden) interactedAt = 0;
    else interaction(event);
  });
  setInterval(pulse, interval);

  function revealCopyButtons() {
    document.querySelectorAll('[data-copy-id]').forEach(button => { button.hidden = false; });
  }
  revealCopyButtons();
  document.addEventListener('nurse:analytics-updated', revealCopyButtons);
  document.addEventListener('click', async event => {
    const button = event.target.closest('[data-copy-id]');
    if (!button) return;
    const value = document.getElementById(button.dataset.copyId);
    const status = button.closest('.settings-detail, .analytics-members')?.querySelector('[data-copy-status]');
    if (!value || !status) return;
    try {
      await navigator.clipboard.writeText(value.textContent.trim());
      status.textContent = 'User ID copied.';
    } catch (_) {
      const range = document.createRange();
      range.selectNodeContents(value);
      const selection = window.getSelection();
      selection.removeAllRanges(); selection.addRange(range);
      status.textContent = 'User ID selected. Use your device’s Copy command.';
    }
  });
})();
